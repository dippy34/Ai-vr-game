/**
 * Write KTX2 copies of every model + surface set from `srcDir` (public/) into `outDir`.
 * Returns a summary (also logged).
 */
export async function optimizeAssets({
  srcDir = join(ROOT, 'public'),
  outDir = join(ROOT, 'dist'),
  cacheDir = join(ROOT, 'node_modules', '.cache', 'mute-ktx2'),
  only = null,
  useCache = true,
  log = (msg) => console.log(msg),
} = {}) {
  const t0 = Date.now();
  const [{ NodeIO }, ext, { default: sharp }] = await Promise.all([
    import('@gltf-transform/core'),
    import('@gltf-transform/extensions'),
    import('sharp'),
  ]);
  const io = new NodeIO().registerExtensions(ext.ALL_EXTENSIONS);
  const opt = new Optimizer({ cacheDir, useCache, log });
  const summary = { models: [], surfaces: [], downloadBefore: 0, downloadAfter: 0 };

  try {
    // ---- Models ---------------------------------------------------------------------------
    const modelsDir = join(srcDir, 'models');
    const outModels = join(outDir, 'models', 'ktx2');
    mkdirSync(outModels, { recursive: true });
    const names = existsSync(modelsDir)
      ? readdirSync(modelsDir).filter((f) => f.endsWith('.glb') && !f.startsWith('_')).map((f) => f.slice(0, -4)).sort()
      : [];
    const converted = [];
    await Promise.all(names.filter((n) => !only || only.includes(n)).map(async (name) => {
      const src = join(modelsDir, `${name}.glb`);
      try {
        const doc = await io.read(src);
        const root = doc.getRoot();
        const graph = doc.getGraph();
        await Promise.all(root.listTextures().map(async (tex, i) => {
          const mime = tex.getMimeType();
          if (!['image/webp', 'image/png', 'image/jpeg'].includes(mime)) return;
          const slots = [...new Set(graph.listParentEdges(tex).filter((e) => e.getParent() !== root).map((e) => e.getName()))];
          const kind = kindOfSlots(slots);
          const label = `${name}:${tex.getName() || i}`;
          const { ktx2, key } = await opt.encodeImage(sharp, tex.getImage(), {
            kind, label, maxSize: maxSizeFor(name, kind), hq: UASTC_NORMALS.test(name),
          });
          tex.setImage(ktx2).setMimeType('image/ktx2');
          // Content hash in the name: identical textures in different GLBs (both hands, the
          // shared painted-wood trim set, flat glass normals) are shared at runtime.
          tex.setName(`${(tex.getName() || `tex${i}`).replace(/#[0-9a-f]{12}$/, '')}#${key.slice(0, 12)}`);
        }));
        if (root.listTextures().some((t) => t.getMimeType() === 'image/ktx2')) {
          doc.createExtension(ext.KHRTextureBasisu).setRequired(true);
        }
        if (!root.listTextures().some((t) => t.getMimeType() === 'image/webp')) {
          for (const e of root.listExtensionsUsed()) if (e.extensionName === 'EXT_texture_webp') e.dispose();
        }
        const bytes = await io.writeBinary(doc);
        writeFileSync(join(outModels, `${name}.glb`), bytes);
        const before = statSync(src).size;
        summary.downloadBefore += before;
        summary.downloadAfter += bytes.byteLength;
        summary.models.push({ name, before, after: bytes.byteLength });
        converted.push(name);
      } catch (e) {
        log(`  ! ${name}.glb not converted (the game will use the WebP original): ${e?.message ?? e}`);
      }
    }));
    // Keep entries from earlier partial runs (--only) that still have their file.
    const listed = new Set(converted);
    for (const n of names) if (!listed.has(n) && existsSync(join(outModels, `${n}.glb`))) listed.add(n);
    writeFileSync(join(outModels, 'manifest.json'), JSON.stringify([...listed].sort()));

    // ---- Surface texture sets -------------------------------------------------------------
    const texDir = join(srcDir, 'textures');
    const indexPath = join(texDir, 'textures.json');
    if (existsSync(indexPath)) {
      const index = JSON.parse(readFileSync(indexPath, 'utf8'));
      const outTex = join(outDir, 'textures');
      mkdirSync(outTex, { recursive: true });
      await Promise.all(Object.entries(index).map(async ([set, info]) => {
        if (only && !only.includes(set) && !only.includes('textures')) return;
        const maps = Array.isArray(info.maps) ? info.maps : ['color', 'normal', 'orm'];
        try {
          await Promise.all(maps.map(async (map) => {
            const src = join(texDir, `${set}_${map}.webp`);
            const kind = map === 'color' ? 'color' : map === 'normal' ? 'normal' : 'data';
            // TextureLoader flips images on upload (flipY), compressed textures can't be: flip here.
            const { ktx2 } = await opt.encodeImage(sharp, readFileSync(src), {
              kind, label: `${set}_${map}`, flipY: true, hq: UASTC_NORMALS.test(`surface:${set}`),
            });
            writeFileSync(join(outTex, `${set}_${map}.ktx2`), ktx2);
            const before = statSync(src).size;
            summary.downloadBefore += before;
            summary.downloadAfter += ktx2.byteLength;
            summary.surfaces.push({ name: `${set}_${map}`, before, after: ktx2.byteLength });
          }));
          info.ktx2 = true;
        } catch (e) {
          log(`  ! surface set ${set} not converted (the game will use WebP): ${e?.message ?? e}`);
          delete info.ktx2;
        }
      }));
      writeFileSync(join(outTex, 'textures.json'), JSON.stringify(index, null, 2));
    }
  } finally {
    await opt.close();
  }

  const s = opt.stats;
  summary.gpuBefore = s.gpuBefore;
  summary.gpuAfter = s.gpuAfter;
  log(
    `[ktx2] ${summary.models.length} models + ${summary.surfaces.length} surface maps, ${s.textures} textures `
    + `(${s.encoded} encoded, ${s.cached} cached) in ${((Date.now() - t0) / 1000).toFixed(1)} s\n`
    + `[ktx2] est. GPU texture memory (all textures, mips, Quest formats): ${fmtMB(s.gpuBefore)} as RGBA8 -> ${fmtMB(s.gpuAfter)}\n`
    + `[ktx2] download: ${fmtMB(summary.downloadBefore)} (WebP) -> ${fmtMB(summary.downloadAfter)} (KTX2)\n`
    + Object.entries(s.byKind).map(([k, v]) => `[ktx2]   ${k.padEnd(9)} ${String(v.count).padStart(3)} textures, GPU ${fmtMB(v.gpu)}, file ${fmtMB(v.bytes)}`).join('\n'),
  );
  return summary;
}

// CLI
if (isMainThread && process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  const flag = (name) => {
    const i = args.indexOf(name);
    if (i < 0) return undefined;
    const v = args[i + 1];
    args.splice(i, 2);
    return v;
  };
  const noCache = args.includes('--no-cache');
  if (noCache) args.splice(args.indexOf('--no-cache'), 1);
  const src = flag('--src');
  const only = flag('--only');
  const outDir = resolve(args[0] ?? join(ROOT, 'dist'));
  if (!existsSync(outDir)) {
    console.error(`[ktx2] output dir ${outDir} does not exist (run vite build first)`);
    process.exit(1);
  }
  optimizeAssets({
    outDir,
    srcDir: src ? resolve(src) : undefined,
    only: only ? only.split(',') : null,
    useCache: !noCache,
  }).catch((e) => {
    console.error('[ktx2] failed:', e);
    process.exit(1);
  });
}
