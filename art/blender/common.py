"""
Shared helpers for MUTE's Blender model scripts.

Every model in the game is generated by a Python script in this folder (models-as-code), so it can
be rebuilt, tweaked and reviewed like any other source file. Scripts run headless through the
`bpy` package (Blender 5.0.1 as a Python module): see art/README.md.

Conventions (the renderer relies on them):
  * Units are meters. Blender is Z-up; the glTF exporter converts to three.js Y-up.
  * The FRONT of every model faces Blender +Y, which becomes three.js -Z (= yaw 0 in the game).
  * Origin: floor contact point (bottom center) for furniture/props/characters, unless the
    asset's README entry says otherwise (e.g. hands: the wrist).
  * glTF only exports IMAGE textures, so procedural materials must be baked (see `bake`).
"""

from __future__ import annotations

import math
import os
from typing import Iterable, Sequence

import bpy
import bmesh
from mathutils import Vector

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
MODELS_DIR = os.path.join(REPO, 'public', 'models')
PREVIEW_DIR = os.path.join(REPO, 'art', 'previews')


# ---------------------------------------------------------------------------------------------
# Scene
# ---------------------------------------------------------------------------------------------

def reset() -> bpy.types.Scene:
    """Empty scene, metric units, Cycles on CPU (the only engine that works headless here)."""
    bpy.ops.wm.read_factory_settings(use_empty=True)
    scene = bpy.context.scene
    scene.unit_settings.system = 'METRIC'
    scene.render.engine = 'CYCLES'
    scene.cycles.device = 'CPU'
    scene.cycles.samples = 32
    return scene


def activate(obj: bpy.types.Object, select: Sequence[bpy.types.Object] | None = None) -> None:
    for o in bpy.context.view_layer.objects:
        o.select_set(False)
    for o in (select or [obj]):
        o.select_set(True)
    bpy.context.view_layer.objects.active = obj


def apply_modifiers(obj: bpy.types.Object) -> None:
    """Bake the modifier stack into the mesh (robust headless; no operator context needed)."""
    deps = bpy.context.evaluated_depsgraph_get()
    mesh = bpy.data.meshes.new_from_object(obj.evaluated_get(deps))
    old = obj.data
    obj.modifiers.clear()
    obj.data = mesh
    if old.users == 0:
        bpy.data.meshes.remove(old)


def apply_transform(obj: bpy.types.Object, location=False, rotation=True, scale=True) -> None:
    activate(obj)
    bpy.ops.object.transform_apply(location=location, rotation=rotation, scale=scale)


def join(objects: Sequence[bpy.types.Object], name: str | None = None) -> bpy.types.Object:
    """Join meshes into the first one (materials are kept per face)."""
    objects = [o for o in objects if o.type == 'MESH']
    target = objects[0]
    with bpy.context.temp_override(
        active_object=target, selected_editable_objects=objects, selected_objects=objects
    ):
        bpy.ops.object.join()
    if name:
        target.name = name
        target.data.name = name
    return target


def smooth(obj: bpy.types.Object, angle_deg: float = 40.0) -> None:
    """Smooth shading with sharp edges kept above `angle_deg`."""
    activate(obj)
    try:
        bpy.ops.object.shade_smooth_by_angle(angle=math.radians(angle_deg))
    except Exception:  # older API fallback
        bpy.ops.object.shade_smooth()


def tri_count(objects: Iterable[bpy.types.Object]) -> int:
    deps = bpy.context.evaluated_depsgraph_get()
    total = 0
    for o in objects:
        if o.type != 'MESH':
            continue
        m = o.evaluated_get(deps).to_mesh()
        m.calc_loop_triangles()
        total += len(m.loop_triangles)
        o.evaluated_get(deps).to_mesh_clear()
    return total


def decimate_to(obj: bpy.types.Object, max_tris: int) -> None:
    """Collapse-decimate a mesh down to roughly `max_tris` triangles (no-op if already under)."""
    current = tri_count([obj])
    if current <= max_tris:
        return
    mod = obj.modifiers.new('decimate', 'DECIMATE')
    mod.ratio = max_tris / current
    mod.use_collapse_triangulate = True
    apply_modifiers(obj)


def uv_unwrap(obj: bpy.types.Object, margin: float = 0.01, angle_deg: float = 66.0) -> None:
    activate(obj)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=math.radians(angle_deg), island_margin=margin)
    bpy.ops.object.mode_set(mode='OBJECT')


def set_origin_bottom_center(obj: bpy.types.Object) -> None:
    """Move the object's origin to the center of its bounding box bottom, then put it at 0,0,0."""
    pts = [obj.matrix_world @ Vector(c) for c in obj.bound_box]
    lo = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    hi = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    pivot = Vector(((lo.x + hi.x) / 2, (lo.y + hi.y) / 2, lo.z))
    obj.data.transform(__import__('mathutils').Matrix.Translation(-(pivot - obj.location)))
    obj.location = (0, 0, 0)


