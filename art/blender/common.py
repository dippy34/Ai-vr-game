# Materials
# ---------------------------------------------------------------------------------------------

def _bsdf(mat: bpy.types.Material) -> bpy.types.Node:
    nt = mat.node_tree
    for n in nt.nodes:
        if n.type == 'BSDF_PRINCIPLED':
            return n
    out = next((n for n in nt.nodes if n.type == 'OUTPUT_MATERIAL'), None) or nt.nodes.new('ShaderNodeOutputMaterial')
    b = nt.nodes.new('ShaderNodeBsdfPrincipled')
    nt.links.new(b.outputs['BSDF'], out.inputs['Surface'])
    return b


def material(
    name: str,
    color=(0.5, 0.5, 0.5),
    roughness: float = 0.6,
    metallic: float = 0.0,
    emission=None,
    emission_strength: float = 1.0,
    alpha: float = 1.0,
) -> bpy.types.Material:
    """Plain Principled BSDF material (exports to glTF as-is, no baking needed)."""
    mat = bpy.data.materials.new(name)
    try:
        mat.use_nodes = True  # deprecated (always on) in newer Blender
    except Exception:
        pass
    b = _bsdf(mat)
    b.inputs['Base Color'].default_value = (*color, 1.0)
    b.inputs['Roughness'].default_value = roughness
    b.inputs['Metallic'].default_value = metallic
    if emission is not None:
        b.inputs['Emission Color'].default_value = (*emission, 1.0)
        b.inputs['Emission Strength'].default_value = emission_strength
    if alpha < 1.0:
        b.inputs['Alpha'].default_value = alpha
        for attr, value in (('surface_render_method', 'BLENDED'), ('blend_method', 'BLEND')):
            try:
                setattr(mat, attr, value)
            except Exception:
                pass
    return mat


def assign(obj: bpy.types.Object, mat: bpy.types.Material) -> None:
    obj.data.materials.clear()
    obj.data.materials.append(mat)


# ---------------------------------------------------------------------------------------------
# Baking (procedural / high-poly detail -> image textures that glTF can carry)
# ---------------------------------------------------------------------------------------------

def _zero_metallic(obj: bpy.types.Object):
    """Set every Principled 'Metallic' on obj's materials to 0 (unlinking textures); returns undo."""
    saved = []
    for mat in obj.data.materials:
        if not mat or not mat.node_tree:
            continue
        nt = mat.node_tree
        for n in nt.nodes:
            if n.type != 'BSDF_PRINCIPLED':
                continue
            sock = n.inputs['Metallic']
            links = [(l.from_socket, l.to_socket) for l in sock.links]
            for l in list(sock.links):
                nt.links.remove(l)
            saved.append((nt, sock, sock.default_value, links))
            sock.default_value = 0.0

    def undo() -> None:
        for nt, sock, value, links in saved:
            sock.default_value = value
            for a, b in links:
                nt.links.new(a, b)

    return undo


def bake(
    low: bpy.types.Object,
    name: str,
    size: int = 1024,
    high: bpy.types.Object | None = None,
    normal: bool = True,
    roughness: bool = True,
    emission: bool = False,
    cage_extrusion: float = 0.03,
    margin: int = 8,
    samples: int = 4,
) -> bpy.types.Material:
    """
    Bake base color (+ roughness, + tangent-space normal, + emission) into images and replace
    `low`'s materials with a single image-textured material named `name`.

    Without `high`, bakes `low`'s own (procedural) materials. With `high`, bakes the high-poly
    object's surface (color + detail normals) onto `low` (selected-to-active). `low` needs UVs
    (call uv_unwrap first) and `high` should overlap `low` closely.
    """
    scene = bpy.context.scene
    scene.render.engine = 'CYCLES'
    scene.cycles.samples = samples

    def new_image(suffix: str, non_color: bool) -> bpy.types.Image:
        img = bpy.data.images.new(f'{name}_{suffix}', size, size, alpha=False, float_buffer=False)
        if non_color:
            img.colorspace_settings.name = 'Non-Color'
        return img

    # Every material on the object being baked INTO needs an active image node pointing at the
    # target image. With selected-to-active that's the low-poly; otherwise also the low-poly.
    if not low.data.materials:
        assign(low, material(f'{name}_tmp'))

    def target(img: bpy.types.Image) -> None:
        for mat in low.data.materials:
            nt = mat.node_tree
            node = nt.nodes.get('__bake_target__') or nt.nodes.new('ShaderNodeTexImage')
            node.name = '__bake_target__'
            node.image = img
            for n in nt.nodes:
                n.select = False
            node.select = True
            nt.nodes.active = node

    sel = [high, low] if high else [low]
    common = dict(margin=margin, use_selected_to_active=bool(high), cage_extrusion=cage_extrusion if high else 0.0)

    passes: list[tuple[str, bpy.types.Image]] = []

    color = new_image('color', False)
    target(color)
    activate(low, sel)
    # Cycles' diffuse-color pass is black on metallic surfaces, so bake color with metalness
    # temporarily at 0 (and unlinked), then restore it.
    source = high if high else low
    restore = _zero_metallic(source)
    try:
        bpy.ops.object.bake(type='DIFFUSE', pass_filter={'COLOR'}, **common)
    finally:
        restore()
    passes.append(('color', color))

    if roughness:
        rough = new_image('rough', True)
        target(rough)
        activate(low, sel)
        bpy.ops.object.bake(type='ROUGHNESS', **common)
        passes.append(('rough', rough))

    if normal:
        nrm = new_image('normal', True)
        target(nrm)
        activate(low, sel)
        bpy.ops.object.bake(type='NORMAL', normal_space='TANGENT', **common)
        passes.append(('normal', nrm))

    if emission:
        emi = new_image('emit', False)
        target(emi)
        activate(low, sel)
        bpy.ops.object.bake(type='EMIT', **common)
        passes.append(('emit', emi))

    for _, img in passes:
        img.pack()

    # Replace with one clean, exporter-friendly material.
    mat = bpy.data.materials.new(name)
    try:
        mat.use_nodes = True
    except Exception:
        pass
    nt = mat.node_tree
    b = _bsdf(mat)
    imgs = dict(passes)

    def tex(img: bpy.types.Image, x: float, y: float) -> bpy.types.Node:
        n = nt.nodes.new('ShaderNodeTexImage')
        n.image = img
        n.location = (x, y)
        return n

    nt.links.new(tex(imgs['color'], -600, 300).outputs['Color'], b.inputs['Base Color'])
    if 'rough' in imgs:
        nt.links.new(tex(imgs['rough'], -600, 0).outputs['Color'], b.inputs['Roughness'])
    if 'normal' in imgs:
        nm = nt.nodes.new('ShaderNodeNormalMap')
        nm.location = (-250, -300)
        nt.links.new(tex(imgs['normal'], -600, -300).outputs['Color'], nm.inputs['Color'])
        nt.links.new(nm.outputs['Normal'], b.inputs['Normal'])
    if 'emit' in imgs:
        nt.links.new(tex(imgs['emit'], -600, -600).outputs['Color'], b.inputs['Emission Color'])
        b.inputs['Emission Strength'].default_value = 1.0
    assign(low, mat)
    return mat


