def export_glb(
    name: str,
    objects: Sequence[bpy.types.Object] | None = None,
    animations: bool = False,
    image_format: str = 'WEBP',
) -> str:
    """Export to public/models/<name>.glb. `objects` = what to export (plus their children)."""
    os.makedirs(MODELS_DIR, exist_ok=True)
    path = os.path.join(MODELS_DIR, f'{name}.glb')
    if objects:
        everything: list[bpy.types.Object] = []
        for o in objects:
            everything.append(o)
            everything.extend(o.children_recursive)
        activate(everything[0], everything)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format='GLB',
        use_selection=bool(objects),
        export_apply=True,
        export_yup=True,
        export_texcoords=True,
        export_tangents=True,
        export_normals=True,
        export_materials='EXPORT',
        export_image_format=image_format,
        export_animations=animations,
        export_animation_mode='ACTIONS',
        export_skins=True,
        export_lights=False,
        export_cameras=False,
        export_extras=True,
    )
    print(f'[export] {path}  ({os.path.getsize(path) / 1024:.0f} KB)')
    return path


def _bounds(objects: Sequence[bpy.types.Object]) -> tuple[Vector, Vector]:
    deps = bpy.context.evaluated_depsgraph_get()
    lo = Vector((1e9, 1e9, 1e9))
    hi = Vector((-1e9, -1e9, -1e9))
    for o in objects:
        if o.type != 'MESH':
            continue
        ev = o.evaluated_get(deps)
        for c in ev.bound_box:
            p = ev.matrix_world @ Vector(c)
            lo = Vector((min(lo.x, p.x), min(lo.y, p.y), min(lo.z, p.z)))
            hi = Vector((max(hi.x, p.x), max(hi.y, p.y), max(hi.z, p.z)))
    return lo, hi


def preview(
    name: str,
    objects: Sequence[bpy.types.Object] | None = None,
    yaw_deg: float = 35.0,
    pitch_deg: float = 15.0,
    size: int = 640,
    mood: str = 'studio',
    samples: int = 48,
    zoom: float = 1.0,
) -> str:
    """
    Render art/previews/<name>.png so the model can be reviewed.
    yaw 0 = looking at the model's FRONT (camera on the +Y side looking toward -Y).
    mood: 'studio' (neutral gray, soft 3-point light) or 'flash' (black room, one hard
    camera-flash light from the viewer, like in game).
    """
    os.makedirs(PREVIEW_DIR, exist_ok=True)
    scene = bpy.context.scene
    objects = list(objects or [o for o in scene.objects if o.type == 'MESH'])
    lo, hi = _bounds(objects)
    center = (lo + hi) / 2
    radius = max((hi - lo).length / 2, 0.05)

    temp: list[bpy.types.Object] = []
    cam_data = bpy.data.cameras.new('__prev_cam')
    cam_data.lens = 50
    cam = bpy.data.objects.new('__prev_cam', cam_data)
    scene.collection.objects.link(cam)
    temp.append(cam)
    fov = 2 * math.atan(cam_data.sensor_width / (2 * cam_data.lens))
    dist = radius / math.sin(fov / 2) * 1.08 / zoom
    yaw, pitch = math.radians(yaw_deg), math.radians(pitch_deg)
    direction = Vector((math.sin(yaw) * math.cos(pitch), math.cos(yaw) * math.cos(pitch), math.sin(pitch)))
    cam.location = center + direction * dist
    cam.rotation_euler = (center - cam.location).to_track_quat('-Z', 'Y').to_euler()
    scene.camera = cam

    def light(kind: str, energy: float, loc: Vector, size_: float = 1.0, color=(1, 1, 1)):
        data = bpy.data.lights.new(f'__prev_{kind}_{len(temp)}', kind)
        data.energy = energy
        data.color = color
        if kind == 'AREA':
            data.size = size_
        if kind == 'SPOT':
            data.spot_size = math.radians(70)
            data.shadow_soft_size = 0.02
        o = bpy.data.objects.new(data.name, data)
        o.location = loc
        o.rotation_euler = (center - loc).to_track_quat('-Z', 'Y').to_euler()
        scene.collection.objects.link(o)
        temp.append(o)

    world = scene.world or bpy.data.worlds.new('World')
    scene.world = world
    try:
        world.use_nodes = True
    except Exception:
        pass
    bg = next((n for n in world.node_tree.nodes if n.type == 'BACKGROUND'), None)
    r = radius * 4
    if mood == 'flash':
        if bg:
            bg.inputs['Color'].default_value = (0.0, 0.0, 0.0, 1)
            bg.inputs['Strength'].default_value = 0.0
        light('SPOT', 18 * r * r, cam.location + Vector((0, 0, 0.05)))
        light('POINT', 2 * r * r, center + Vector((-r, -r, r)), color=(0.55, 0.65, 1.0))
    else:
        if bg:
            bg.inputs['Color'].default_value = (0.18, 0.18, 0.19, 1)
            bg.inputs['Strength'].default_value = 0.6
        light('AREA', 60 * r * r, center + Vector((r, r * 0.6, r * 1.2)), size_=r)
        light('AREA', 20 * r * r, center + Vector((-r * 1.2, r * 0.4, r * 0.4)), size_=r)
        light('AREA', 40 * r * r, center + Vector((0, -r * 1.3, r)), size_=r)

    scene.cycles.samples = samples
    scene.render.resolution_x = size
    scene.render.resolution_y = size
    scene.render.film_transparent = False
    path = os.path.join(PREVIEW_DIR, f'{name}.png')
    scene.render.filepath = path
    bpy.ops.render.render(write_still=True)

    for o in temp:
        data = o.data
        bpy.data.objects.remove(o)
        if isinstance(data, bpy.types.Camera):
            bpy.data.cameras.remove(data)
        elif isinstance(data, bpy.types.Light):
            bpy.data.lights.remove(data)
    print(f'[preview] {path}')
    return path


def report(name: str, objects: Sequence[bpy.types.Object]) -> None:
    print(f'[report] {name}: {tri_count(objects)} triangles, {len(objects)} objects')
